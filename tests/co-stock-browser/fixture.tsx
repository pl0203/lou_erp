import React from 'react';
import {createRoot} from 'react-dom/client';
import {createMemoryRouter,RouterProvider} from 'react-router-dom';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import COCustomerStock from '../../src/pages/athel/co/COCustomerStock';
import {fixture,customer} from './boundary';
import '../../src/index.css';
const client=new QueryClient({defaultOptions:{queries:{retry:false},mutations:{retry:false}}});
const router=createMemoryRouter([{path:'/athel/co/stock',element:<COCustomerStock/>}],{initialEntries:[`/athel/co/stock?customer=${customer}&sku=SKU-1`]});
Object.assign(window,{fixture,fixtureRouter:router,refreshStock:()=>client.invalidateQueries({predicate:q=>q.queryKey[4]==='customer-stock-v2'})});
createRoot(document.getElementById('root')!).render(<QueryClientProvider client={client}><main style={{padding:24}}><p>LOCAL SYNTHETIC TEST — no hosted account or data</p><RouterProvider router={router}/></main></QueryClientProvider>);
